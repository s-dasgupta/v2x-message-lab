import { useEffect, useRef } from 'react';
import { useApp } from '../app/state';
import { href } from '../app/router';
import { describeType } from '../asn1/types';
import { ENTRIES, entry, fieldByPath, fixedUperBits, type CatalogEntry } from '../j2735/catalog';
import { AtLeast, Ref } from './common';
import { Pipeline } from './Pipeline';

/** Resolves a path ("coreData.speed", "value.coreData.speed") or an entity id ("DE_Speed"). */
export function resolveDetail(key: string): { entry: CatalogEntry; path?: string } | null {
  const spec = fieldByPath(key);
  if (spec) return { entry: entry(spec.entityId), path: spec.path };
  const e = ENTRIES.find((x) => x.id === key);
  return e ? { entry: e } : null;
}

export function EntryFacts({ e, path }: { e: CatalogEntry; path?: string }) {
  const spec = path ? fieldByPath(path) : undefined;
  const bits = fixedUperBits(e.type);
  const parent = spec ? ENTRIES.find((x) => x.id === spec.parentId) : undefined;
  return (
    <dl>
      <dt>J2735 entity</dt>
      <dd>
        <code>{e.id}</code> <Ref s={e.section} />
      </dd>
      {spec && (
        <>
          <dt>Component</dt>
          <dd>
            <code>{spec.component}</code> in <code>{parent?.type.name ?? spec.parentId}</code>
          </dd>
          <dt>Path</dt>
          <dd><code>{spec.path}</code></dd>
          <dt>Presence</dt>
          <dd>{spec.required ? 'Mandatory (no OPTIONAL keyword)' : 'OPTIONAL'}</dd>
          <dt>Value origin</dt>
          <dd>{{ sensor: 'Measured (sensor / vehicle bus / GNSS)', system: 'System-generated by the on-board unit', configuration: 'Static vehicle configuration', structure: 'Container (data frame)' }[spec.origin]}</dd>
        </>
      )}
      <dt>ASN.1 type</dt>
      <dd><code>{e.type.name}</code> ::= <code className="small">{describeType(e.type)}</code></dd>
      {e.unit && (<><dt>Unit</dt><dd>{e.unit}</dd></>)}
      {e.resolution && (<><dt>Resolution (LSB)</dt><dd>{e.resolution}</dd></>)}
      {e.physicalRange && (<><dt>Physical range</dt><dd>{e.physicalRange}</dd></>)}
      {bits !== undefined && (<><dt>UPER width</dt><dd>{bits} bit{bits === 1 ? '' : 's'}</dd></>)}
      {e.specialValues && e.specialValues.length > 0 && (
        <>
          <dt>Special values</dt>
          <dd>
            {e.specialValues.map((s) => (
              <div key={s.code}>
                <code>{s.code}</code> — {s.meaning}
              </div>
            ))}
          </dd>
        </>
      )}
    </dl>
  );
}

export function EntryExplanation({ e }: { e: CatalogEntry }) {
  return (
    <div className="qa">
      <h4>What is this field?</h4>
      <p>{e.what}</p>
      <h4>Where does the value come from?</h4>
      <p>{e.source}</p>
      <h4>Why is it needed in V2X communication?</h4>
      <p>{e.why}</p>
      {e.conversion && (
        <>
          <h4>How is it converted?</h4>
          <p>{e.conversion}</p>
        </>
      )}
      <AtLeast min="engineering">
        <h4>How is it represented?</h4>
        <p>{e.representation}</p>
      </AtLeast>
      {e.unavailable && (
        <>
          <h4>What if the value is unavailable?</h4>
          <p>{e.unavailable}</p>
        </>
      )}
      <h4>Where is it defined?</h4>
      <p>
        SAE J2735 (SEP2024) <Ref s={e.section} />. Section numbers point to the official SAE publication; this tool does not reproduce its text.
      </p>
      {e.notes && e.notes.length > 0 && (
        <>
          <h4>Notes</h4>
          {e.notes.map((n, i) => (
            <p key={i} className="small">
              <span className={`note-tag ${n.authority}`}>{n.authority}</span>
              {n.text}
            </p>
          ))}
        </>
      )}
    </div>
  );
}

export function FieldDetailDrawer() {
  const { detail, openDetail, build, encoding } = useApp();
  const closeRef = useRef<HTMLButtonElement>(null);
  useEffect(() => {
    if (!detail) return;
    closeRef.current?.focus();
    const onKey = (e: KeyboardEvent) => e.key === 'Escape' && openDetail(null);
    window.addEventListener('keydown', onKey);
    return () => window.removeEventListener('keydown', onKey);
  }, [detail, openDetail]);
  if (!detail) return null;
  const resolved = resolveDetail(detail);
  if (!resolved) return null;
  const { entry: e, path } = resolved;
  const conversion = path ? build.conversions[path] : undefined;
  const span = path && encoding?.ok ? encoding.result.frame.trace.spans.find((s) => s.path === `value.${path}` && s.kind === 'value') : undefined;
  return (
    <>
      <div className="drawer-backdrop" onClick={() => openDetail(null)} />
      <aside className="drawer" role="dialog" aria-modal="true" aria-label={`Details for ${e.id}`}>
        <div className="card-head">
          <div>
            <div className="muted small">{e.kind.replace('-', ' ')}</div>
            <h2 style={{ margin: 0 }}>{fieldByPath(path ?? '')?.label ?? e.type.name}</h2>
          </div>
          <button ref={closeRef} onClick={() => openDetail(null)} aria-label="Close details">
            ✕
          </button>
        </div>
        <p className="muted">{e.summary}</p>
        <EntryFacts e={e} path={path} />
        {conversion && (
          <AtLeast min="engineering">
            <h3 style={{ marginTop: 16 }}>Current transformation</h3>
            <Pipeline c={conversion} compact />
          </AtLeast>
        )}
        {span && (
          <AtLeast min="advanced">
            <h3 style={{ marginTop: 16 }}>Encoded bits (MessageFrame)</h3>
            <p className="small">
              Bits {span.start}–{span.start + span.length - 1} ({span.length} bits): <code className="v-bits">{span.fieldValue !== undefined && span.length <= 52 ? span.fieldValue.toString(2).padStart(span.length, '0') : '—'}</code>
              <br />
              {span.note}. <a href={href('bits', path)} onClick={() => openDetail(null)}>Open in the bit explorer</a>
            </p>
          </AtLeast>
        )}
        <EntryExplanation e={e} />
        <p className="small" style={{ marginTop: 16 }}>
          <a href={href('reference', e.id)} onClick={() => openDetail(null)}>Open in the Standard Reference Explorer</a>
        </p>
      </aside>
    </>
  );
}
