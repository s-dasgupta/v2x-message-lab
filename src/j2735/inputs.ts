/**
 * The vehicle-measurement model entered in the BSM Generator.
 *
 * Numeric inputs are kept as the text the user typed (so that validation can
 * report exactly what was wrong) together with a unit and an explicit
 * "unavailable" flag. Nothing in this file knows about J2735 encodings.
 */
import type { AccelUnit, ElevationUnit, LengthUnit, SpeedUnit, YawUnit } from './conversions/units';

export interface NumericInput<U extends string = string> {
  /** The number as typed by the user. */
  value: string;
  unit: U;
  /** True when the sensor/source reports the quantity as unavailable. */
  unavailable: boolean;
}

export type TransmissionChoice = 'neutral' | 'park' | 'forwardGears' | 'reverseGears' | 'unavailable';
export type SystemStatusChoice = 'unavailable' | 'off' | 'on' | 'engaged';
export type BoostChoice = 'unavailable' | 'off' | 'on';
export type AuxBrakeChoice = 'unavailable' | 'off' | 'on';

export interface WheelBrakesInput {
  /** Brake-applied status cannot be determined. */
  unavailable: boolean;
  leftFront: boolean;
  leftRear: boolean;
  rightFront: boolean;
  rightRear: boolean;
}

/** Measured or configured vehicle data (everything a human/sensor supplies). */
export interface VehicleInputs {
  latitude: NumericInput<'deg'>;
  longitude: NumericInput<'deg'>;
  elevation: NumericInput<ElevationUnit>;
  /** Seconds within the current UTC minute at the time of the position fix (0 – 60.999, 60.x = leap second). */
  utcSecond: NumericInput<'s'>;
  semiMajor: NumericInput<'m'>;
  semiMinor: NumericInput<'m'>;
  orientation: NumericInput<'deg'>;
  transmission: TransmissionChoice;
  speed: NumericInput<SpeedUnit>;
  heading: NumericInput<'deg'>;
  steeringWheelAngle: NumericInput<'deg'>;
  accelLong: NumericInput<AccelUnit>;
  accelLat: NumericInput<AccelUnit>;
  accelVert: NumericInput<AccelUnit>;
  yawRate: NumericInput<YawUnit>;
  wheelBrakes: WheelBrakesInput;
  traction: SystemStatusChoice;
  abs: SystemStatusChoice;
  scs: SystemStatusChoice;
  brakeBoost: BoostChoice;
  auxBrakes: AuxBrakeChoice;
  vehicleWidth: NumericInput<LengthUnit>;
  vehicleLength: NumericInput<LengthUnit>;
}

/** Values generated by the on-board unit, not measured by a sensor. */
export interface SystemInputs {
  /** DE_MsgCount sequence number, 0..127. */
  msgCount: number;
  /** DE_TemporaryID as 8 hexadecimal digits. */
  temporaryId: string;
}

export type InputKey = keyof VehicleInputs;

export function num<U extends string>(value: number | string, unit: U, unavailable = false): NumericInput<U> {
  return { value: String(value), unit, unavailable };
}
