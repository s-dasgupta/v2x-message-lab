/**
 * Generates docs/FIELD_TRACEABILITY.md from the schema and catalog, so the
 * field table can never disagree with the code. Run: npx tsx scripts/generate-field-traceability.ts
 */
import { writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { describeType } from '../src/asn1/types';
import { FIELD_SPECS, entry, fixedUperBits } from '../src/j2735/catalog';

const CONVERTER: Record<string, string> = {
  'coreData.msgCnt': 'convertMsgCount', 'coreData.id': 'convertTemporaryId', 'coreData.secMark': 'convertSecMark',
  'coreData.lat': 'convertLatitude', 'coreData.long': 'convertLongitude', 'coreData.elev': 'convertElevation',
  'coreData.accuracy.semiMajor': 'convertSemiMajor', 'coreData.accuracy.semiMinor': 'convertSemiMinor',
  'coreData.accuracy.orientation': 'convertOrientation', 'coreData.transmission': 'convertTransmission',
  'coreData.speed': 'convertSpeed', 'coreData.heading': 'convertHeading', 'coreData.angle': 'convertSteeringWheelAngle',
  'coreData.accelSet.long': 'convertAccelLong', 'coreData.accelSet.lat': 'convertAccelLat', 'coreData.accelSet.vert': 'convertAccelVert',
  'coreData.accelSet.yaw': 'convertYawRate', 'coreData.brakes.wheelBrakes': 'convertWheelBrakes', 'coreData.brakes.traction': 'convertTraction',
  'coreData.brakes.abs': 'convertAbs', 'coreData.brakes.scs': 'convertScs', 'coreData.brakes.brakeBoost': 'convertBrakeBoost',
  'coreData.brakes.auxBrakes': 'convertAuxBrakes', 'coreData.size.width': 'convertVehicleWidth', 'coreData.size.length': 'convertVehicleLength',
};

const rows = FIELD_SPECS.map((f) => {
  const e = entry(f.entityId);
  const special = (e.specialValues ?? []).map((s) => `${s.code}: ${s.meaning}`).join('; ') || (e.unavailable ? e.unavailable : '—');
  return `| \`${f.path}\` | ${e.id} | §${e.section} | \`${describeType(e.type).replace(/\|/g, '\\|')}\` | ${fixedUperBits(e.type) ?? 'var.'} | ${e.unit ?? '—'} | ${e.resolution ?? '—'} | ${special.replace(/\|/g, '\\|')} | ${f.origin} | ${CONVERTER[f.path] ? `\`${CONVERTER[f.path]}\`` : '(frame)'} |`;
});

const doc = `# Field-level traceability — BSM Part I (generated)

Generated by \`scripts/generate-field-traceability.ts\` from \`src/j2735/schema\` and
\`src/j2735/catalog\`. Do not edit by hand.

Every row is mandatory (DF_BSMcoreData has no OPTIONAL components, §6.10).
Conversion functions live in \`src/j2735/conversions/fields.ts\` and are tested in
\`tests/unit/conversions.test.ts\`; encodings are tested in \`tests/unit/bsm-codec.test.ts\`,
\`tests/unit/bit-trace.test.ts\`, \`tests/unit/reference-vectors.test.ts\` and cross-validated by
\`tools/validation/cross_validate.py\`.

| Path | J2735 entity | Section | ASN.1 constraint | UPER bits | Unit | LSB | Special values | Origin | Converter |
|---|---|---|---|---|---|---|---|---|---|
${rows.join('\n')}
`;

const out = resolve(dirname(fileURLToPath(import.meta.url)), '..', 'docs', 'FIELD_TRACEABILITY.md');
writeFileSync(out, doc);
console.log(`wrote ${out}`);
